// 특별 규칙 (우선순위 높음)
function specialRules(m) {
  // 쿠팡: 쿠팡이츠만 식비, 나머지 쇼핑
  if (m.includes('쿠팡이츠')) return '식비';
  if (m.includes('쿠팡')) return '쇼핑·생활용품';
  // 책방/문고는 교육 (이미 키워드에 있음)
  return null;
}

export function classify(merchant) {
  const m = (merchant || '').trim();
  const sp = specialRules(m);
  if (sp) return sp;
  for (const cat of CATEGORIES) {
    if (cat.name === '기타') continue;
    for (const kw of cat.keywords) {
      if (m.includes(kw)) return cat.name;
    }
  }
  return '기타';
}

